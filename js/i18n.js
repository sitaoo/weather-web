  // Browser language mapped onto supported codes; falls back to zh.
  function defaultLang() {
    try {
      const nav = (navigator.languages && navigator.languages.length ? navigator.languages : [navigator.language]) || [];
      const codes = LANGUAGES.map((l) => l.code);
      for (const tag of nav) {
        if (!tag) continue;
        const t = String(tag).toLowerCase();
        if (codes.includes(t)) return t;
        const primary = t.split('-')[0];
        if (codes.includes(primary)) return primary;
      }
    } catch { /* keep fallback */ }
    return 'zh';
  }
  // Traditional Chinese (zh-tw) is derived from zh at init via the vendored
  // transverter (single 30KB script, no network). Falls back to zh when the
  // library is unavailable (e.g. data-raw extractor running under node).
  // idioms=false skips Taiwan idiom replacement (for proper nouns: place
  // names must convert char-by-char, e.g. 华盛顿镇区 -> 華盛頓鎮區).
  function toTraditional(s, idioms = true) {
    try {
      if (typeof window !== 'undefined' && window.transverter) {
        return window.transverter({ type: 'traditional', str: String(s), language: idioms ? 'zh_TW' : '' });
      }
    } catch { /* keep fallback */ }
    return String(s);
  }
  function toSimplified(s) {
    try {
      if (typeof window !== 'undefined' && window.transverter) {
        return window.transverter({ type: 'simplified', str: String(s), language: 'zh_TW' });
      }
    } catch { /* keep fallback */ }
    return String(s);
  }
  function genTraditional(src) {
    if (typeof src === 'string') return toTraditional(src);
    if (Array.isArray(src)) return src.map(genTraditional);
    if (src && typeof src === 'object') {
      const out = {};
      for (const k of Object.keys(src)) out[k] = genTraditional(src[k]);
      return out;
    }
    return src;
  }
